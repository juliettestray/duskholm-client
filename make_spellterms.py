"""Builds spellterms.py: the game's own words that the Windows spell checker does not already know.

    python make_spellterms.py [more_words.txt ...]     (spellterms_source.txt and the seed words below are always included)

Each candidate is checked against the Windows dictionary and kept only if it is flagged, so the list holds just
what is needed. Run it again whenever the word list changes. Only public words belong here: this file is in the repository."""
import os
import sys

import winspell

SEED = """Duskholm Haven Sanctuary dhampir dhampirs moroi truesight mindhack electropathy electropath shadowwalk
shadowwalking teletext storyrunner storyrunners Fleshformed Foxhound OOC IC RP GMCP MSDP MSSP MXP MUD MUDs""".split()


def main(paths):
    words = set(SEED)
    here = os.path.dirname(os.path.abspath(__file__))
    paths = [os.path.join(here, "spellterms_source.txt")] + list(paths)
    for p in paths:
        with open(p, encoding="utf-8", errors="replace") as f:
            for line in f:
                w = line.strip()
                if w and not w.startswith("#"):
                    words.add(w)
    sp = winspell.WinSpell.create()
    if sp is None:
        sys.exit("The Windows spell checker is not available here.")
    keep = sorted({w.casefold() for w in words if len(w) > 1 and sp.check(w)}, key=str.casefold)
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "spellterms.py")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write('"""The game\'s own words the Windows spell checker does not know (generated by make_spellterms.py; lower case)."""\n')
        f.write("TERMS = frozenset(\"\"\"\n")
        line = ""
        for w in keep:
            if len(line) + len(w) + 1 > 110:
                f.write(line.rstrip() + "\n")
                line = ""
            line += w + " "
        f.write(line.rstrip() + "\n\"\"\".split())\n")
    print("%d of %d words were not in the %s dictionary: kept." % (len(keep), len(words), sp.language))


if __name__ == "__main__":
    main(sys.argv[1:])
